import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const fontsDir = path.join(root, "assets/fonts");
const pages = [];

async function collectPages(dir) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".") || ["node_modules", "dist"].includes(entry.name)) continue;
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) await collectPages(file);
    else if (entry.name.endsWith(".html")) pages.push(file);
  }
}

async function download(url) {
  const response = await fetch(url, {
    headers: { "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36" },
  });
  if (!response.ok) throw new Error(`Font download failed: ${response.status}`);
  return response;
}

await collectPages(root);
if (process.argv.includes("--include-drafts")) await collectPages(path.join(root, ".drafts"));
let text = Array.from({ length: 95 }, (_, index) => String.fromCharCode(index + 32)).join("") + "\u00a0\u00a9\u00ae";
for (const file of pages) text += await fs.readFile(file, "utf8");
const characters = [...new Set([...text].filter(char => char.codePointAt(0) >= 32))].sort().join("");
const coveragePath = path.join(fontsDir, "coverage.json");

if (process.argv.includes("--check")) {
  const coverage = JSON.parse(await fs.readFile(coveragePath, "utf8"));
  const missing = [...characters].filter(char => !coverage.characters.includes(char));
  if (missing.length) {
    console.error(`Missing font characters: ${missing.join("")}. Run node scripts/update-fonts.mjs.`);
    process.exitCode = 1;
  } else console.log(`Font coverage OK for ${pages.length} pages.`);
} else {
  await fs.mkdir(fontsDir, { recursive: true });
  let css = "/* Generated by scripts/update-fonts.mjs. SIL OFL licenses: assets/fonts/. */\n";
  const used = new Set();
  let japaneseFont;
  for (const [family, subset] of [
    ["Noto Serif JP:wght@400..700", characters],
    ["Cormorant Garamond:wght@500..600", [...characters].filter(char => char.codePointAt(0) < 256).join("")],
  ]) {
    const url = new URL("https://fonts.googleapis.com/css2");
    url.searchParams.set("family", family);
    url.searchParams.set("text", subset);
    url.searchParams.set("display", "swap");
    let fontCss = await (await download(url)).text();
    // Google Fonts returns uniform @font-face declarations; replace only source URLs.
    const sources = [...new Set([...fontCss.matchAll(/url\((https:\/\/[^)]+)\)/g)].map(match => match[1]))];
    for (const source of sources) {
      const data = Buffer.from(await (await download(source)).arrayBuffer());
      if (data.toString("ascii", 0, 4) !== "wOF2") throw new Error("Expected a WOFF2 font.");
      const hash = crypto.createHash("sha256").update(data).digest("hex").slice(0, 16);
      const filename = `font-${hash}.woff2`;
      used.add(filename);
      await fs.writeFile(path.join(fontsDir, filename), data);
      fontCss = fontCss.replaceAll(source, `/assets/fonts/${filename}`);
      if (family.startsWith("Noto")) japaneseFont = filename;
    }
    css += fontCss;
  }
  await fs.writeFile(path.join(root, "assets/css/fonts.css"), css);
  await fs.writeFile(coveragePath, JSON.stringify({ characters }, null, 2) + "\n");
  for (const file of pages) {
    let html = await fs.readFile(file, "utf8");
    html = html.replace(/^[ \t]*<link rel="preload" as="font"[^\n]*\r?\n/gm, "");
    html = html.replace('<link rel="stylesheet" href="/assets/css/fonts.css', `<link rel="preload" as="font" href="/assets/fonts/${japaneseFont}" type="font/woff2" crossorigin />\n    <link rel="stylesheet" href="/assets/css/fonts.css`);
    await fs.writeFile(file, html);
  }
  // Only remove files in this generator's hashed namespace, never licenses or other assets.
  for (const filename of await fs.readdir(fontsDir)) {
    if (/^font-[a-f0-9]{16}\.woff2$/.test(filename) && !used.has(filename)) {
      await fs.unlink(path.join(fontsDir, filename));
    }
  }
  console.log(`Generated ${used.size} font files for ${characters.length} characters across ${pages.length} pages.`);
}
